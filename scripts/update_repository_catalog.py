#!/usr/bin/env python3
"""Generate a repository catalogue and refresh the profile dashboard using GitHub API metadata."""
import os
import sys
from datetime import datetime, timezone
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

API = "https://api.github.com"
OWNER = os.environ.get("GITHUB_OWNER", "NayumAhmed")
PROFILE_REPO = os.environ.get("GITHUB_PROFILE_REPO", f"{OWNER}/{OWNER}")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
OUTPUT = os.environ.get("REPOSITORY_CATALOG_PATH", "REPOSITORY_CATALOG.md")
README = os.environ.get("PROFILE_README_PATH", "README.md")
WORKFLOW_FILE = ".github/workflows/repository-discovery.yml"

def request_json(url):
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "NayumAhmed-Repository-Dashboard",
    }
    if TOKEN:
        headers["Authorization"] = "Bearer " + TOKEN
    try:
        with urlopen(Request(url, headers=headers), timeout=30) as response:
            import json
            return response.status, json.loads(response.read().decode())
    except HTTPError as error:
        body = error.read().decode(errors="replace")
        print(f"GitHub API error {error.code}: {body[:300]}", file=sys.stderr)
        return error.code, {}
    except (URLError, TimeoutError) as error:
        print(f"GitHub API request failed: {error}", file=sys.stderr)
        return 0, {}

def esc(value):
    return str(value or "").replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()

def main():
    if not TOKEN:
        print("ERROR: GITHUB_TOKEN is required.", file=sys.stderr)
        return 2

    repos = []
    page = 1
    while True:
        params = urlencode({"per_page": 100, "page": page, "type": "owner", "sort": "full_name", "direction": "asc"})
        status, data = request_json(f"{API}/users/{OWNER}/repos?{params}")
        if status != 200 or not isinstance(data, list):
            return 1
        repos.extend(data)
        if len(data) < 100:
            break
        page += 1

    repos.sort(key=lambda r: (not bool(r.get("fork")), (r.get("name") or "").lower()))
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    fork_count = sum(1 for repo in repos if repo.get("fork"))
    original_count = len(repos) - fork_count

    run_status = "No completed runs found"
    run_time = "Not available yet"
    run_url = f"https://github.com/{PROFILE_REPO}/actions/workflows/repository-discovery.yml"
    runs_url = f"{API}/repos/{PROFILE_REPO}/actions/workflows/repository-discovery.yml/runs?per_page=10"
    run_code, run_data = request_json(runs_url)
    if run_code == 200:
        completed = [run for run in run_data.get("workflow_runs", []) if run.get("status") == "completed"]
        if completed:
            last = completed[0]
            run_status = str(last.get("conclusion") or "completed").replace("_", " ").title()
            raw_time = last.get("updated_at") or last.get("created_at") or ""
            try:
                run_time = datetime.fromisoformat(raw_time.replace("Z", "+00:00")).astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
            except ValueError:
                run_time = raw_time or "Not available"
            run_url = last.get("html_url") or run_url
    else:
        run_status = "Unavailable (check workflow permissions)"

    lines = [
        "<!-- This file is generated by scripts/update_repository_catalog.py. Do not edit manually. -->",
        "# GitHub Repository Catalogue",
        "",
        f"> Automatically generated from the repositories owned by **{OWNER}**. Last refreshed: {now}.",
        "",
        f"**Total repositories: {len(repos)}** · **Forks: {fork_count}** · **Standalone repositories: {original_count}** · [Open all repositories](https://github.com/{OWNER}?tab=repositories) · [Discovery workflow](https://github.com/{PROFILE_REPO}/actions/workflows/repository-discovery.yml)",
        "",
        "This catalogue lists repository metadata only. A fork is not a security review; inspect its source, dependencies, licence, and permissions before running code.",
        "",
        "| Repository | Type | Description | Language | Licence | Stars | Last updated |",
        "|---|---|---|---|---|---:|---|",
    ]
    for repo in repos:
        name = repo.get("name", "")
        url = repo.get("html_url", f"https://github.com/{OWNER}/{name}")
        parent = (repo.get("parent") or {}).get("full_name") or ""
        is_fork = bool(repo.get("fork"))
        kind = f"Fork of [{esc(parent)}](https://github.com/{parent})" if is_fork and parent else ("Fork" if is_fork else "Original")
        language = repo.get("language") or "—"
        license_name = ((repo.get("license") or {}).get("spdx_id") or "Not specified")
        updated = (repo.get("updated_at") or "")[:10] or "—"
        lines.append(
            f"| [{esc(name)}]({url}) | {kind} | {esc(repo.get('description') or '—')} | "
            f"{esc(language)} | {esc(license_name)} | {int(repo.get('stargazers_count') or 0)} | {updated} |"
        )
    lines += [
        "",
        "## Keep this catalogue current",
        "",
        "The Repository Discovery and Safe Forks GitHub Actions workflow regenerates this file after each run. The workflow status and latest completed run are also linked from the profile dashboard.",
        "",
    ]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines))

    dashboard = f"""<!-- REPOSITORY_DASHBOARD_START -->
<div align="center">

| 📦 Repositories in account | 🍴 Forks | 🛠️ Standalone repositories | ⚙️ Last completed discovery run |
|:---:|:---:|:---:|:---:|
| <strong>{len(repos)}</strong> | <strong>{fork_count}</strong> | <strong>{original_count}</strong> | <a href="{run_url}">{esc(run_status)}</a><br/><sub>{esc(run_time)}</sub> |

<a href="https://github.com/{OWNER}?tab=repositories"><img src="https://img.shields.io/badge/REPOSITORIES-{len(repos)}-2563EB?style=for-the-badge&logo=github" alt="Repository count"/></a>
<a href="https://github.com/{PROFILE_REPO}/actions/workflows/repository-discovery.yml"><img src="https://img.shields.io/badge/DISCOVERY-WORKFLOW-DB2777?style=for-the-badge&logo=githubactions" alt="Open discovery workflow"/></a>
<a href="{run_url}"><img src="https://img.shields.io/badge/LAST%20RUN-{esc(run_status).upper().replace(' ', '%20')}-0F766E?style=for-the-badge" alt="Last workflow result"/></a>

<sub>Dashboard snapshot refreshed {now}. Repository count is read from GitHub's repository API. Last-run details are read from GitHub Actions.</sub>

</div>
<!-- REPOSITORY_DASHBOARD_END -->"""
    try:
        with open(README, "r", encoding="utf-8") as file:
            readme = file.read()
    except FileNotFoundError:
        print(f"ERROR: {README} not found; catalogue generated but profile dashboard could not be refreshed.", file=sys.stderr)
        return 1

    start = "<!-- REPOSITORY_DASHBOARD_START -->"
    end = "<!-- REPOSITORY_DASHBOARD_END -->"
    if start in readme and end in readme:
        before, remainder = readme.split(start, 1)
        _, after = remainder.split(end, 1)
        readme = before + dashboard + after
    else:
        section = "\n## 📈 Live repository dashboard\n\nLive snapshot of the repository inventory and latest completed discovery run.\n\n" + dashboard + "\n\n---\n"
        anchor = "## 🧭 Your dashboard"
        if anchor in readme:
            readme = readme.replace(anchor, section + "\n" + anchor, 1)
        else:
            readme += "\n" + section
    with open(README, "w", encoding="utf-8", newline="\n") as file:
        file.write(readme)

    print(f"Generated {OUTPUT} with {len(repos)} repositories ({fork_count} forks). Refreshed profile dashboard; last completed workflow: {run_status} at {run_time}.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
