#!/usr/bin/env python3
"""Generate a Markdown catalogue of repositories owned by the configured GitHub user.

Uses only GitHub repository metadata. It does not clone or execute repository code.
Requires GITHUB_TOKEN and optionally GITHUB_OWNER.
"""
import os
import sys
from datetime import datetime, timezone
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen

API = "https://api.github.com"
OWNER = os.environ.get("GITHUB_OWNER", "NayumAhmed")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
OUTPUT = os.environ.get("REPOSITORY_CATALOG_PATH", "REPOSITORY_CATALOG.md")

def request_json(url):
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "NayumAhmed-Repository-Catalogue",
    }
    if TOKEN:
        headers["Authorization"] = "Bearer " + TOKEN
    req = Request(url, headers=headers)
    try:
        with urlopen(req, timeout=30) as response:
            import json
            return response.status, json.loads(response.read().decode())
    except HTTPError as error:
        body = error.read().decode(errors="replace")
        print(f"GitHub API error {error.code}: {body[:500]}", file=sys.stderr)
        return error.code, {}
    except (URLError, TimeoutError) as error:
        print(f"GitHub API request failed: {error}", file=sys.stderr)
        return 0, {}

def esc(value):
    return str(value or "").replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()

def main():
    if not TOKEN:
        print("ERROR: GITHUB_TOKEN is required.", file=sys.stderr)
        return 2

    repos = []
    page = 1
    while True:
        params = urlencode({"per_page": 100, "page": page, "type": "owner", "sort": "full_name", "direction": "asc"})
        status, data = request_json(f"{API}/users/{OWNER}/repos?{params}")
        if status != 200 or not isinstance(data, list):
            return 1
        repos.extend(data)
        if len(data) < 100:
            break
        page += 1

    repos.sort(key=lambda r: (not bool(r.get("fork")), (r.get("name") or "").lower()))
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "<!-- This file is generated by scripts/update_repository_catalog.py. Do not edit manually. -->",
        "# GitHub Repository Catalogue",
        "",
        f"> Automatically generated from the repositories owned by **{OWNER}**. Last updated: {now}.",
        "",
        f"**Total repositories: {len(repos)}** · [Open all repositories](https://github.com/{OWNER}?tab=repositories) · [Discovery workflow](https://github.com/{OWNER}/{OWNER}/actions/workflows/repository-discovery.yml)",
        "",
        "This catalogue lists repository metadata only. A fork is not a security review; inspect its source, dependencies, licence, and permissions before running code.",
        "",
        "| Repository | Type | Description | Language | Licence | Stars | Last updated |",
        "|---|---|---|---|---|---:|---|",
    ]
    for repo in repos:
        name = repo.get("name", "")
        url = repo.get("html_url", f"https://github.com/{OWNER}/{name}")
        parent = (repo.get("parent") or {}).get("full_name") or ""
        is_fork = bool(repo.get("fork"))
        kind = f"Fork of [{esc(parent)}](https://github.com/{parent})" if is_fork and parent else ("Fork" if is_fork else "Original")
        language = repo.get("language") or "—"
        license_name = ((repo.get("license") or {}).get("spdx_id") or "Not specified")
        updated = (repo.get("updated_at") or "")[:10] or "—"
        lines.append(
            f"| [{esc(name)}]({url}) | {kind} | {esc(repo.get('description') or '—')} | "
            f"{esc(language)} | {esc(license_name)} | {int(repo.get('stargazers_count') or 0)} | {updated} |"
        )
    lines += [
        "",
        "## Keep this catalogue current",
        "",
        "The Repository Discovery and Safe Forks GitHub Actions workflow regenerates this file after each run, including scheduled runs. Newly created forks appear after GitHub makes them visible through the repository API.",
        "",
    ]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines))
    print(f"Generated {OUTPUT} with {len(repos)} repositories.")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
